import assert from 'node:assert/strict';
import { emptyDuelStore, transition, snapshot } from '../server/durableDuel';
const questions=Array.from({length:5},(_,i)=>({id:i+1,vi:'Xin chào',hints:'hello',answers:['Hello'],category:'general'}));
let now=100000;
const db=emptyDuelStore();
const send=(key:string,cmd:any)=>transition(db,key,cmd,now,questions);
for(const id of ['a','b','c','d'])transition(db,id,{type:'register_lobby'},now,questions,{id,name:id,email:`${id}@test.invalid`});
send('a',{type:'find_match'});send('b',{type:'find_match'});
send('c',{type:'find_match'});send('d',{type:'find_match'});
assert.equal(db.sessions.a.roomId,db.sessions.b.roomId);
assert.notEqual(db.sessions.a.roomId,db.sessions.c.roomId);
assert.equal(Object.keys(db.rooms).length,2);
now+=3100;send('a',{type:'poll'});
for(const key of ['a','b']) {
  send(key,{type:'submit_answer',questionIndex:0,answer:'Hello!',requestId:'answer-0'});
  send(key,{type:'submit_answer',questionIndex:0,answer:'Hello!',requestId:'answer-0'});
  assert.equal(db.rooms[db.sessions[key].roomId!].players[key].currentQuestionIndex,1);
  assert.throws(()=>send(key,{type:'submit_answer',questionIndex:0,answer:'Hello'}));
}
assert.equal(db.rooms[db.sessions.a.roomId!].players.a.score,150);
assert.equal(db.rooms[db.sessions.a.roomId!].players.b.score,100);
for(let i=1;i<5;i++)for(const k of ['a','b'])send(k,{type:'skip_question',questionIndex:i});
assert.equal(db.rooms[db.sessions.a.roomId!].status,'finished');
send('a',{type:'request_rematch'});send('b',{type:'request_rematch'});
assert.equal(db.rooms[db.sessions.a.roomId!].status,'countdown');
send('b',{type:'leave_room'});
assert.equal(db.rooms[db.sessions.a.roomId!].winnerId,'a');
send('a',{type:'leave_room'});send('a',{type:'join_room'});
send('a',{type:'send_invite',targetEmail:'b@test.invalid'});
const invitation=snapshot(db,'b',0,now).events.findLast(e=>e.type==='duel_invitation');
assert.throws(()=>send('c',{type:'respond_invite',inviteId:invitation.inviteId,accept:true}));
send('b',{type:'respond_invite',inviteId:invitation.inviteId,accept:true});
assert.equal(db.sessions.a.roomId,db.sessions.b.roomId);
assert.throws(()=>send('a',{type:'start_game'}));
send('b',{type:'toggle_ready'});send('a',{type:'start_game'});
now+=59000;send('a',{type:'poll'});now+=2000;send('a',{type:'poll'});
assert.equal(db.rooms[db.sessions.a.roomId!].winnerId,'a');
assert.equal(db.sessions.b,undefined);
const view=snapshot(db,'a',0,now);assert.equal(view.state.members,undefined);
console.log('PASS: independent pairs, duplicate request/answer protection, scores, rematch, invitations, membership, readiness, expiry, snapshot privacy');
